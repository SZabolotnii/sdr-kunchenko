"""
EstemPMM oracle bridge.

This module is a thin Python wrapper around the R package EstemPMM
(`https://cran.r-project.org/web/packages/EstemPMM/`) which is the reference
implementation for all PMM-related math used in this project.

Strategy: never reimplement PMM in Python. Instead, route all PMM calls through
rpy2 to the canonical R implementation, and write Python tests against
`tests/fixtures/pmm_reference.json` (generated by `scripts/p0_estempmm_oracle.R`).

Notes:
- rpy2 falls back to ABI mode on macOS Homebrew R (libRblas.dylib path mismatch).
  Functionality is identical, ~2x per-call overhead vs API mode. Acceptable for
  Phase 1 sanity; revisit if profiling shows >2h/experiment.
- Each Python process owns one R session. For joblib parallelism use the loky
  backend (process-based) — every worker independently imports this module.
"""
from __future__ import annotations

import os
import subprocess
import warnings


def _detect_r_home() -> str:
    """Resolve R_HOME dynamically so a Homebrew R version bump never breaks the
    rpy2 bridge. Prefers an explicit ``R_HOME`` env var, then ``R RHOME``, and
    only falls back to a hardcoded Homebrew path as a last resort."""
    env_home = os.environ.get("R_HOME")
    if env_home and os.path.isdir(env_home):
        return env_home
    try:
        home = subprocess.check_output(["R", "RHOME"], text=True).strip()
        if home and os.path.isdir(home):
            return home
    except (subprocess.SubprocessError, OSError):
        pass
    return "/opt/homebrew/Cellar/r/4.5.2_1/lib/R"


# rpy2 needs R_HOME before import; detect it instead of pinning a R version.
os.environ["R_HOME"] = _detect_r_home()

with warnings.catch_warnings():
    warnings.simplefilter("ignore")
    import rpy2.robjects as ro  # noqa: E402
    from rpy2.robjects import default_converter, numpy2ri, pandas2ri  # noqa: E402
    from rpy2.robjects.conversion import localconverter  # noqa: E402
    from rpy2.robjects.packages import importr  # noqa: E402

import numpy as np

# rpy2 3.6+ uses context-based conversion. We build a global converter so all
# callers in this module see automatic numpy ↔ R conversion.
_NP_CONV = default_converter + numpy2ri.converter + pandas2ri.converter


def _r_call(callable_fn, *args, **kwargs):
    """Run an R call inside the numpy/pandas converter context."""
    with localconverter(_NP_CONV):
        return callable_fn(*args, **kwargs)


_estempmm = importr("EstemPMM")
_base = importr("base")
_methods = importr("methods")  # for slot() — S4 generic
_stats = importr("stats")

# Suppress R's `cat()` chatter that comes through the rpy2 callback when
# pmm3 is asked to fit asymmetric residuals. The Python pmm_dispatch
# already chooses the correct track; we still call lm_pmm3 unconditionally
# in the experiment harness for benchmarking.
ro.r("options(warn=-1)")  # demote R warnings to silent
ro.r("suppressMessages(suppressWarnings(library(EstemPMM)))")

ESTEMPMM_VERSION: str = str(ro.r('packageVersion("EstemPMM")'))


# -------------------------------------------------------------------- moments


def _as_float_vec(x: np.ndarray) -> ro.FloatVector:
    return ro.FloatVector(np.asarray(x, dtype=float).ravel())


def _scalar(r_obj) -> float:
    """Extract a scalar float from an R numeric of length 1."""
    return float(np.asarray(r_obj).ravel()[0])


def _named_list_to_dict(r_list) -> dict:
    return {n: np.asarray(r_list[i]) for i, n in enumerate(r_list.names)}


def compute_moments(residuals: np.ndarray) -> dict[str, float]:
    """EstemPMM::compute_moments — central moments m2..m6 + std cumulants.

    Bypasses the numpy converter so the result stays as ListVector with
    `rx2` access; we still feed the input via FloatVector explicitly.
    """
    out = _estempmm.compute_moments(_as_float_vec(residuals))
    return {n: float(np.asarray(out.rx2(n)).ravel()[0]) for n in out.names}


def compute_moments_pmm3(residuals: np.ndarray) -> dict[str, float]:
    """EstemPMM::compute_moments_pmm3 — m2,m4,m6 + γ₄,γ₆,g₃,κ for symmetric track."""
    out = _estempmm.compute_moments_pmm3(_as_float_vec(residuals))
    return {n: float(np.asarray(out.rx2(n)).ravel()[0]) for n in out.names}


def cumulants(residuals: np.ndarray) -> dict[str, float]:
    """Standardized cumulants γ₃, γ₄, γ₆ via EstemPMM utilities."""
    v = _as_float_vec(residuals)
    return {
        "gamma3": _scalar(_estempmm.pmm_skewness(v)),
        "gamma4": _scalar(_estempmm.pmm_kurtosis(v)),
        "gamma6": _scalar(_estempmm.pmm_gamma6(v)),
    }


# ---------------------------------------------------------- variance factors


def variance_factor_g2(m2: float, m3: float, m4: float) -> float:
    """g₂ = 1 − γ₃²/(2 + γ₄). EstemPMM returns list(c3, c4, g); we take $g.

    Bypass active converter so result stays as ListVector (with `.rx2`).
    """
    out = _estempmm.pmm2_variance_factor(float(m2), float(m3), float(m4))
    return float(np.asarray(out.rx2("g")).ravel()[0])


def variance_factor_g3(m2: float, m4: float, m6: float) -> float:
    """g₃ = 1 − γ₄²/(6 + 9γ₄ + γ₆). EstemPMM returns list(c4, c6, g); we take $g."""
    out = _estempmm.pmm3_variance_factor(float(m2), float(m4), float(m6))
    return float(np.asarray(out.rx2("g")).ravel()[0])


def variance_factor_full(m2: float, m3: float, m4: float) -> dict:
    """Full PMM2 variance-factor decomposition: c3 (γ₃), c4 (γ₄), g."""
    out = _estempmm.pmm2_variance_factor(float(m2), float(m3), float(m4))
    return {n: float(np.asarray(out.rx2(n)).ravel()[0]) for n in ("c3", "c4", "g")}


# ----------------------------------------------------------------- regression


def _build_lm_dataframe(y: np.ndarray, X: np.ndarray) -> tuple:
    """Construct an R data.frame and a no-intercept formula for `y ~ X`."""
    n, p = X.shape
    with localconverter(_NP_CONV):
        cols = {"y": ro.FloatVector(y.astype(float))}
        cols.update({f"x{i}": ro.FloatVector(X[:, i].astype(float))
                     for i in range(p)})
        df = ro.DataFrame(cols)
    rhs = " + ".join(f"x{i}" for i in range(p)) + " - 1"
    formula = ro.Formula(f"y ~ {rhs}")
    return df, formula


def lm_pmm2(y: np.ndarray, X: np.ndarray, *, max_iter: int = 50,
            tol: float = 1e-6, verbose: bool = False) -> dict:
    """Linear regression via PMM2 (asymmetric track). Wraps EstemPMM::lm_pmm2.

    Parameters
    ----------
    y : (n,) response
    X : (n, p) regressor matrix (no intercept added — pass explicitly)

    Returns
    -------
    dict with keys: coef, residuals, fitted, plus any S4 slots present
                     (m2, m3, m4, gamma3, gamma4, g_coefficient, ...).
    """
    if X.ndim == 1:
        X = X.reshape(-1, 1)
    df, formula = _build_lm_dataframe(y, X)
    with localconverter(_NP_CONV):
        fit = _estempmm.lm_pmm2(formula, data=df, max_iter=max_iter, tol=tol,
                                 verbose=verbose)
    return _unpack_pmm_fit(fit)


def lm_pmm3(y: np.ndarray, X: np.ndarray, *, max_iter: int = 100,
            tol: float = 1e-6, verbose: bool = False) -> dict:
    """Linear regression via PMM3 (symmetric platykurtic track). EstemPMM::lm_pmm3."""
    if X.ndim == 1:
        X = X.reshape(-1, 1)
    df, formula = _build_lm_dataframe(y, X)
    with localconverter(_NP_CONV):
        fit = ro.r("function(f, d) suppressWarnings(EstemPMM::lm_pmm3(f, data=d, verbose=FALSE))")(
            formula, df
        )
    return _unpack_pmm_fit(fit)


# Actual S4 slots:
#   PMM2fit: coefficients, residuals, m2, m3, m4, convergence, iterations, call
#   PMM3fit: coefficients, residuals, m2, m4, m6, gamma4, gamma6, g_coefficient,
#            kappa, convergence, iterations, call
# Derived quantities (not stored) are computed below.
_PMM2_SLOTS = ["m2", "m3", "m4", "convergence", "iterations"]
_PMM3_SLOTS = ["m2", "m4", "m6", "gamma4", "gamma6", "g_coefficient", "kappa",
               "convergence", "iterations"]


def _unpack_pmm_fit(fit) -> dict:
    """Convert an S4 PMM2fit/PMM3fit object into a plain Python dict.

    EstemPMM exports its own S4 generics (`coef`, `residuals`, `fitted`)
    that dispatch on PMM2fit / PMM3fit. Calling `stats::coef` directly
    fails with `$ operator not defined for S4 class`.
    """
    with localconverter(_NP_CONV):
        coef = np.asarray(_estempmm.coef(fit)).ravel().copy()
        resid = np.asarray(_estempmm.residuals(fit)).ravel().copy()
        fitted = np.asarray(_estempmm.fitted(fit)).ravel().copy()
        cls = list(ro.r("class")(fit))[0]

    out: dict = {"coef": coef, "residuals": resid, "fitted": fitted, "class": cls}
    slot_names = _PMM2_SLOTS if cls == "PMM2fit" else _PMM3_SLOTS

    for slot in slot_names:
        try:
            val = _methods.slot(fit, slot)
            arr = np.asarray(val).ravel()
            if arr.dtype.kind == "b":
                out[slot] = bool(arr[0]) if arr.size == 1 else arr
            elif arr.size == 1:
                out[slot] = float(arr[0])
            else:
                out[slot] = arr.copy()
        except Exception:
            continue

    # Derived quantities for PMM2 — not stored as slots in EstemPMM.
    if cls == "PMM2fit":
        m2, m3, m4 = out["m2"], out["m3"], out["m4"]
        sigma = m2**0.5
        out["sigma"] = sigma
        out["gamma3"] = m3 / sigma**3 if sigma > 0 else 0.0
        out["gamma4"] = m4 / m2**2 - 3.0 if m2 > 0 else 0.0
        out["g_coefficient"] = variance_factor_g2(m2, m3, m4)
    else:  # PMM3fit
        out["sigma"] = out["m2"] ** 0.5

    # Normalize convergence flag name → `converged` for downstream code.
    if "convergence" in out:
        out["converged"] = bool(out["convergence"]) if not isinstance(out["convergence"], bool) else out["convergence"]

    return out


# ------------------------------------------------------------------- dispatch


def pmm_dispatch(residuals: np.ndarray, *,
                 symmetry_threshold: float = 0.3,
                 kurtosis_threshold: float = -0.7,
                 g2_threshold: float = 0.95,
                 verbose: bool = False) -> dict:
    """EstemPMM::pmm_dispatch. Returns dict with chosen method and rationale.

    NB: under the active numpy/pandas converter, EstemPMM's named list
    becomes a `rpy2.rlike.container.NamedList` whose `.names` is a method.
    We bypass that path by *not* using a converter for this call.
    """
    out = _estempmm.pmm_dispatch(_as_float_vec(residuals),
                                  symmetry_threshold=symmetry_threshold,
                                  kurtosis_threshold=kurtosis_threshold,
                                  g2_threshold=g2_threshold,
                                  verbose=verbose)
    # Native ListVector — `.names` is a property here.
    result: dict = {}
    for n in out.names:
        elem = out.rx2(n)
        arr = np.asarray(elem).ravel()
        if arr.dtype.kind in {"U", "S", "O"}:
            result[n] = str(arr[0]) if arr.size == 1 else [str(x) for x in arr]
        elif arr.dtype.kind == "b":
            result[n] = bool(arr[0]) if arr.size == 1 else arr.copy()
        elif arr.size == 1:
            val = arr[0]
            result[n] = float(val) if arr.dtype.kind == "f" else val.item()
        else:
            result[n] = arr.copy()
    return result


